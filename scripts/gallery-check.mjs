// CI check: lot page gallery on desktop and iPhone, including the arrows, the counter and "See all photos".
import puppeteer from "puppeteer-core";
import fs from "node:fs";
const [base, path] = process.argv.slice(2);
fs.mkdirSync("shots", { recursive: true });
const b = await puppeteer.launch({ executablePath: process.env.CHROME, args: ["--no-sandbox"] });
const errors = [];
const d = await b.newPage();
d.on("pageerror", (e) => errors.push(e.message));
await d.setViewport({ width: 1400, height: 1000 });
await d.goto(base + path, { waitUntil: "networkidle2", timeout: 60000 });
await d.screenshot({ path: "shots/g-desktop.png", clip: { x: 0, y: 0, width: 1400, height: 1000 } });
await d.click(".gallery-next"); await new Promise((r) => setTimeout(r, 700));
await d.click(".gallery-next"); await new Promise((r) => setTimeout(r, 700));
console.log("desktop counter after 2 clicks:", await d.$eval("[data-gallery-counter]", (e) => e.textContent));
await d.click(".gallery-all"); await new Promise((r) => setTimeout(r, 800));
await d.screenshot({ path: "shots/g-all.png" });
const m = await b.newPage();
m.on("pageerror", (e) => errors.push(e.message));
await m.setUserAgent("Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/18.0 Mobile/15E148 Safari/604.1");
await m.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await m.goto(base + path, { waitUntil: "networkidle2", timeout: 60000 });
console.log("mobile width:", await m.evaluate(() => innerWidth));
await m.evaluate(() => { const s = document.querySelector("[data-gallery]"); s.scrollTo({ left: s.clientWidth * 3, behavior: "instant" }); });
await new Promise((r) => setTimeout(r, 600));
console.log("mobile counter after swipe to 4:", await m.$eval("[data-gallery-counter]", (e) => e.textContent));
await m.screenshot({ path: "shots/g-mobile.png", clip: { x: 0, y: 0, width: 390, height: 844 } });
await m.tap(".catmenu > summary"); await new Promise((r) => setTimeout(r, 300));
await m.screenshot({ path: "shots/g-menu.png", clip: { x: 0, y: 0, width: 390, height: 844 } });
console.log("page errors:", errors.length ? errors.join(" | ") : "none");
await b.close();
